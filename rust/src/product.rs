//! Static knowledge about JetBrains products: settings prefixes, app names,
//! CLI binary names, and Alfred keywords.

#[derive(Clone, Debug)]
pub struct Product {
    /// Stable identifier used by `--product` and config overrides.
    pub id: &'static str,
    /// Human-readable product name.
    pub name: &'static str,
    /// Prefix of the settings directory, e.g. `IntelliJIdea2026.2`.
    pub preference_prefix: &'static str,
    /// Application bundle stems, e.g. `IntelliJ IDEA`.
    pub application_names: &'static [&'static str],
    /// Executable names inside `Contents/MacOS` or on `PATH`.
    pub binaries: &'static [&'static str],
    /// Extra Alfred query prefixes, e.g. `idea` or `ij`.
    pub keywords: &'static [&'static str],
    /// Fleet/Air store projects in `backend/**/trusted-paths.xml`.
    pub fleet: bool,
}

